# DECLARACÃO DO VALOR A VARIAVEL
pontuacao = 10

# IMPRIMINDO O VALOR E MOSTRANDO O TIPO
print(f"Esta variavel tem o valor: ", {pontuacao} | type(pontuacao))

# REATRIBUINDO A MESMA VARIAVEL E SOMANDO 15
pontuacao = pontuacao + 15

# IMPRIMINDO O NOVO VALOR
print(f"Esta variavel tem o valor: ", {pontuacao} | type(pontuacao))

# ATRIBUINDO UM NOVO VALOR A ESSA VARIAVEL
pontuacao = "Nivel Avançado"

# IMPRIMINDO ESSE NOVO VALOR E O NOVO TIPO 
print(f"Esta variavel tem o valor: ", {pontuacao} | type(pontuacao))