# EXEMPLO 01:

# AO MESMO TEMPO QUE SE ESTÁ DECLARANDO AS VARIAVEIS, SOLICITE O DADO AO USUÁRIO
N1 = float(input("Informe um numero: "))
N2 = float(input("Informe outro numero: "))

# EXEMPLO COM A SOMA
soma = N1 + N2
print("O resultado da soma é: ", soma)

# EXEMPLO COM A SUBTRAÇÃO
sub = N1 - N2
print("O resultado da subtração é: ", sub)

# EXEMPLO COM A MULTIPLICAÇÃO
multi = N1 * N2
print("O resultado da multiplicação é: ", multi)

# EXEMPLO COM A DIVISÃO
divisao = N1 / N2
print("O resultado da divisão é: ", divisao)

# EXEMPLO COM A DIVISÃO POR INTEIRO (QUOCIENTE)
divInteiro = int(N1 / N2)
print("O resultado da divisão por inteiro é: ", divInteiro)

# EXEMPLO COM A DIVISÃO POR INTEIRO (RESTO DA DIVISÃO)
divResto = int(N1 % N2)
print("O resultado da divisão por inteiro é: ", divResto)