# EXEMPLO 02:

# DECLAREI UMA VARIAVEL COM CONTEÚDO ARBITRÁRIO
dado = 10

print(f"Conteúdo da variavel dado: {dado}")

# USANDO OPERADORES ARITMÉTICOS COM ATRIBUIÇÃO

# SOMA
dado += 2
print("Atribuição de soma: ", dado)

# SUBTRAÇÃO
dado -= 2
print("Atribuição de subtração: ", dado)

# MULTIPLICAÇÃO
dado *= 2
print("Atribuição de multiplicação: ", dado)

# DIVISÃO
dado /= 2
print("Atribuição de divisão: ", dado)

# RESTO DA DIVISÃO INTEIRA
dado %= 3
print("Atribuição de resto da divisão inteira: ", dado)