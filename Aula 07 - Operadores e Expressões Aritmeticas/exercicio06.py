# DECLARE A VARIAVEL SALDO COM O VALOR
saldo = 1000.0

# INFORME O VALOR DO DEPOSITO RECEBIDO
valor = float(input("Informe o valor do deposito recebido: "))

# FAÇA A ATRIBUIÇÃO DE VALOR JUNTO DA SOMA
saldo += valor

# IMPRIMA O RESULTADO
print(f"O valor recebido foi R$ {saldo: .2f}")