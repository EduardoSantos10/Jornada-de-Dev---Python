# INFORME 3 VALORES
V1 = int(input("Informe um valor: "))
V2 = int(input("Informe um valor: "))
V3 = int(input("Informe um valor: "))

# COM A FUNÇÃO "MAX()" E PASSANDO AS VARIAVEIS COMO PARAMETROS
# VOCÊ QUER SABER QUAL É O MAIOR NÚMERO
maior = max(V1, V2, V3)

# COM A FUNÇÃO "MIN()" E PASSANDO AS VARIAVEIS COMO PARAMETROS
# VOCÊ QUER SABER QUAL É O MENOR NÚMERO
menor = min(V1, V2, V3)

# IMPRIMI O ENUNCIADO COM O RESULTADO DA COMPARAÇÃO
print("A maior carga registrada foi no servidor foi", maior)
print("A menor carga registrada foi no servidor foi", menor)