# CONFORME O ENUNCIADO, SOLICITEI 2 VALORES
valor01 = int(input("Informe o primeiro valor: "))
valor02 = int(input("Informe o segundo valor valor: "))

# REALIZEI A SUBTRAÇÃO DO VALOR 01 COM O VALOR 02
resultado = valor01 - valor02

# ATRIBUI O RESULTADO DENTRO DA FUNÇÃO ABS, PARA MOSTRAR A DIFERENÇA
ms = abs(resultado)

# IMPRIMI A MENSAGEM COM O RESULTADO
print("A diferença absoluta é", ms, "milissegundos!")