# EXERCICIO 10: FILTRAGEM CONDICIONAL (ÍMPARES 1 A 15 COM % E IF)

# LAÇO FOR PARA IDENTIFICAR E IMPRIMIR OS NÚMEROS ÍMPARES
for i in range(1, 16, 1):
    # SE O RESULTADO DO NÚMERO QUE FOR DIVISÍVEL POR 2, FOR DIFERENTE DE 0, ELE ÍMPAR
    if i % 2 != 0: # FORMULA
        print(f"O número {i} é ímpar") # IMPRIMINDO O RESULTADO