# EXERCICIO 05: SOMA ACUMULADA DE RECURSOS (1 A 100)

# NESTE EXERCÍCIO, VOCÊ PRECISARÁ DE UMA VARIÁVEL ACUMULADORA QUE INICIE EM 0
soma_total = 0

# CRIE O LAÇO PARA PERCORRER DE 1 A 100, DE 1 EM 1
for i in range(1, 101, 1):
    soma_total += i # A CADA ITERAÇÃO, SOME O VALOR DE 1 EM 1 E ACUMULE NA VARIÁVEL ACUMULADORA
    
print("A soma total de 1 a 100 é", soma_total) # EXIBA O RESULTADO JUNTO DE UMA MENSAGEM