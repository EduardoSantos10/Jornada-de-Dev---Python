# EXERCICIO 09: QUADRADO DOS VALORES (1 A 10)

# CRIAÇÃO DE LAÇO PARA CALCULAR O QUADRADO DE CADA VALOR A CADA ITERAÇÃO DO CONTADOR
for i in range(1, 11, 1): # DE 1 A 10
    quad = i ** 2 # A CADA ITERAÇÃO, REALIZA O CALCULO DO QUADRADO DE CADA NÚMERO E INSERE NA VARIAVEL "QUAD"
    print(quad, " ") # IMPRIME A MENSAGEM
